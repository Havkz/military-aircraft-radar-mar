    static String fromHex(String rawHex) {
        if (rawHex == null) return "";
        String hex = rawHex.replace("~", "").trim().toUpperCase(Locale.US);
        if (!hex.matches("[0-9A-F]{6}")) return "";
        int address;
        try { address = Integer.parseInt(hex, 16); }
        catch (NumberFormatException ignored) { return ""; }
        for (int i = 0; i < RANGES.length; i++) {
            if (address >= RANGES[i][0] && address <= RANGES[i][1]) return COUNTRIES[i];
        }
        return "";
    }

    static String providerOrHex(String providerCountry, String hex) {
        String value = providerCountry == null ? "" : providerCountry.trim();
        if (!value.isEmpty() && !"-".equals(value)
                && !"n/a".equalsIgnoreCase(value)) return value;
        return fromHex(hex);
    }
